function getLanguage() {
    const saved = localStorage.getItem('language');
    if (saved) return saved;
    const browserLang = navigator.language.split('-')[0];
    if (['en', 'uk', 'de', 'pl'].includes(browserLang)) return browserLang;
    return 'en';
}

function setLanguage(lang) {
    localStorage.setItem('language', lang);
    applyTranslations();
}

function t(key) {
    const lang = getLanguage();
    const keys = key.split('.');
    let value = translations[lang];
    for (const k of keys) {
        value = value[k];
        if (!value) return key;
    }
    return value;
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    
    const langSelector = document.createElement('div');
    langSelector.className = 'language-selector';
    langSelector.innerHTML = `
        <select onchange="setLanguage(this.value)" style="position:fixed;top:20px;right:20px;padding:10px;font-size:16px;border:2px solid #000;border-radius:5px;background:#fff;z-index:1000;">
            <option value="en" ${getLanguage()==='en'?'selected':''}>English</option>
            <option value="uk" ${getLanguage()==='uk'?'selected':''}>Українська</option>
            <option value="de" ${getLanguage()==='de'?'selected':''}>Deutsch</option>
            <option value="pl" ${getLanguage()==='pl'?'selected':''}>Polski</option>
        </select>
    `;
    document.body.appendChild(langSelector);
});
